    moist: 'Moist',
    'Rain detected': 'Rain detected',
    'No rain': 'No rain',
    'Fault reported': 'Fault reported',
    'Pump start confirmed': 'Pump start confirmed',
    'Pump stop confirmed': 'Pump stop confirmed',
    'Irrigation started': 'Irrigation started',
    'Irrigation stopped': 'Irrigation stopped',
    'Refill started': 'Refill started',
    'Refill stopped': 'Refill stopped',
    'Command accepted': 'Command accepted',
